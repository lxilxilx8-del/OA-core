import sys
from pathlib import Path
sys.path.insert(0,str(Path(__file__).parent/"app"))
import ast
import hashlib
import json
import os
from pathlib import Path
import tempfile
import threading
import time
import unittest
from unittest.mock import Mock

from image_cache import IMAGE_RETENTION_SECONDS, cleanup_image_cache, parse_image_notes
import test_web_search as chat_tests


class ImageCacheTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory(dir=Path(__file__).parent)
        self.root = Path(self.temp.name)
        self.now = time.time()
    def tearDown(self):
        self.temp.cleanup()

    def image(self, number, days):
        path = self.root / f'wechat_inbound_{number:032x}.png'
        path.write_bytes(b'synthetic image')
        stamp = self.now - days * 86400
        os.utime(path, (stamp, stamp))
        return path

    def test_eight_day_policy_keeps_recent_images_and_all_text_memory(self):
        old, recent, boundary = self.image(1, 9), self.image(2, 7), self.image(3, 8)
        originals = {}
        for name in ['user_memory.json', 'chat_history.json', 'conversation.sqlite3', 'my-photo.png', 'tray_icon.png']:
            path = self.root / name
            path.write_bytes(b'must remain unchanged')
            os.utime(path, (self.now - 30 * 86400,) * 2)
            originals[path] = hashlib.sha256(path.read_bytes()).hexdigest()
        nested = self.root / 'backup'
        nested.mkdir()
        nested_image = nested / old.name
        nested_image.write_bytes(b'not a live direct-child cache')
        result = cleanup_image_cache(self.root, now=self.now)
        self.assertEqual(IMAGE_RETENTION_SECONDS, 8 * 86400)
        self.assertEqual(result['deleted'], 2)
        self.assertFalse(old.exists())
        self.assertFalse(boundary.exists())
        self.assertTrue(recent.exists())
        self.assertTrue(nested_image.exists())
        for path, digest in originals.items():
            self.assertEqual(hashlib.sha256(path.read_bytes()).hexdigest(), digest)

    def test_explicitly_protected_expired_image_is_kept(self):
        image = self.image(1, 10)
        result = cleanup_image_cache(self.root, now=self.now, protected=[image])
        self.assertEqual(result['deleted'], 0)
        self.assertTrue(image.exists())

    def maintenance(self, states=None):
        path = Path(__file__).parent/'app'/'clawbot_service.py'
        node = next(n for n in ast.parse(path.read_text(encoding='utf-8')).body
                    if isinstance(n, ast.FunctionDef) and n.name == 'maintain_image_cache')
        env = {'INBOX_LOCK': threading.Lock(), 'MERGE_LOCK': threading.RLock(), 'MERGE_STATES': states or {},
               'AGY_CALL_LOCK': threading.Lock(), 'BASE_DIR': str(self.root), 'log': Mock()}
        exec(compile(ast.Module(body=[node], type_ignores=[]), str(path), 'exec'), env)
        return env

    def test_no_cleanup_during_running_or_queued_model_work(self):
        image = self.image(1, 10)
        env = self.maintenance({'owner': {'images': [str(image)]}})
        self.assertFalse(env['maintain_image_cache']())
        self.assertTrue(image.exists())
        env['MERGE_STATES'].clear()
        with env['INBOX_LOCK']:
            self.assertFalse(env['maintain_image_cache']())
        self.assertTrue(image.exists())
        with env['AGY_CALL_LOCK']:
            self.assertFalse(env['maintain_image_cache']())
        self.assertTrue(image.exists())
        self.assertTrue(env['maintain_image_cache']())
        self.assertFalse(image.exists())
        self.assertFalse(env['INBOX_LOCK'].locked())

    def test_future_timestamp_and_unrelated_similar_names_are_kept(self):
        future = self.image(1, -1)
        unrelated = self.root / 'wechat_inbound_personal.png'
        unrelated.write_bytes(b'not generated by the downloader')
        os.utime(unrelated, (self.now - 30 * 86400,) * 2)
        self.assertEqual(cleanup_image_cache(self.root, now=self.now)['deleted'], 0)
        self.assertTrue(future.exists())
        self.assertTrue(unrelated.exists())

    def test_internal_notes_only_accept_bounded_valid_numbered_descriptions(self):
        payload = {'images': [{'index': 2, 'summary': '第二张是一张蓝色示意图。'},
                              {'index': 1, 'summary': 'a' * 500},
                              {'index': True, 'summary': 'invalid'}, {'index': 9, 'summary': 'invalid'}]}
        reply, notes = parse_image_notes('回答。<image_notes>' + json.dumps(payload) + '</image_notes>', 3)
        self.assertEqual(reply, '回答。')
        self.assertEqual(len(notes), 2)
        self.assertTrue(notes[0].startswith('第1张：'))
        self.assertEqual(len(notes[0].split('：')[1]), 200)

    def test_malformed_metadata_does_not_leak_into_wechat(self):
        for text in ['回答。<image_notes>not json</image_notes>', '回答。<image_notes>{"unfinished":']:
            reply, notes = parse_image_notes(text, 3)
            self.assertEqual(reply, '回答。')
            self.assertEqual(notes, [])

    def test_visual_summary_is_saved_as_assistant_history_not_a_user_fact(self):
        image = self.image(1, 0)
        metadata = '<image_notes>{"images":[{"index":1,"summary":"画面是一张红色示意图。"}]}</image_notes>'
        env = chat_tests.ChatIntegrationTests().chat(['图片是红色的。' + metadata])
        reply = env['ask_ai_chat']('', '', '', '', '看看', [str(image)])
        self.assertEqual(reply, '图片是红色的。')
        env['invoke_agy_llm'].assert_called_once()
        env['add_user_memory'].assert_not_called()
        history = env['save_history'].call_args.args[0]
        self.assertEqual(history[-1]['role'], 'assistant')
        self.assertIn('模型生成', history[-1]['content'])
        self.assertIn('红色示意图', history[-1]['content'])
        self.assertNotIn('<image_notes>', history[-1]['content'])
        self.assertNotIn('示意图', history[-2]['content'])


if __name__ == '__main__':
    unittest.main()
